#!/usr/bin/env python3
"""Rebuild exact-name EG2-4C2 assets and an explicitly experimental assembly."""

from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import tempfile
import xml.etree.ElementTree as ET

import mujoco
import numpy as np

from realman_rl_simtoreal.paths import GRIPPER_ASSETS as ASSETS, ROBOT_ASSETS

INTERNAL_PAIRS = [('4C2_baselink', f'4C2_Link{i}') for i in range(1, 5)] + [
    ('4C2_Link1', '4C2_Link2'), ('4C2_Link3', '4C2_Link4'),
    ('4C2_Link2', '4C2_Link5'), ('4C2_Link3', '4C2_Link6')]


def numbers(values):
    return ' '.join(format(float(v), '.17g') for v in values)


def write(root, path):
    ET.indent(root, space='  ')
    ET.ElementTree(root).write(path, encoding='utf-8', xml_declaration=True)


def build():
    manifest = json.loads((ASSETS/'upstream_manifest.json').read_text())
    for row in manifest['files']:
        data = (ASSETS/'upstream'/row['local_path']).read_bytes()
        if hashlib.sha256(data).hexdigest() != row['sha256']:
            raise ValueError(f"Upstream checksum mismatch: {row['local_path']}")
    urdf = ET.parse(ASSETS/'upstream/EG2-4C2.urdf').getroot()
    if urdf.get('name') != 'EG2-4C2':
        raise ValueError('Wrong gripper model')
    for mesh in urdf.findall('.//mesh'):
        mesh.set('filename', 'upstream/meshes/'+Path(mesh.get('filename')).name)
    extension = ET.SubElement(urdf, 'mujoco')
    ET.SubElement(extension, 'compiler', discardvisual='false', fusestatic='false',
                  strippath='false', inertiafromgeom='false', balanceinertia='false')
    compatible = ASSETS/'eg2_4c2_mujoco.urdf'
    write(urdf, compatible)
    source = mujoco.MjModel.from_xml_path(str(compatible))
    if (source.nq, source.nv, source.neq) != (6, 6, 5):
        raise ValueError('Expected six hinges and five imported mimic equalities')
    with tempfile.TemporaryDirectory(prefix='eg2-export-') as directory:
        export = Path(directory)/'model.xml'
        mujoco.mj_saveLastXML(str(export), source)
        root = ET.parse(export).getroot()
    root.set('model', 'EG2-4C2 upstream kinematics; uncalibrated dynamics')
    root.insert(0, ET.Comment('Generated by build_gripper_model.py; see SOURCE.md. Original geometry/limits retained.'))
    root.find('compiler').set('fusestatic', 'false')
    for mesh in root.findall('asset/mesh'):
        mesh.set('file', 'upstream/meshes/'+Path(mesh.get('file')).name)
    ET.SubElement(root, 'option', timestep='0.002', gravity='0 0 -9.81', integrator='implicitfast')
    for body in root.findall('.//body'):
        original = source.body(body.get('name'))
        body.set('pos', numbers(original.pos))
        body.set('quat', numbers(original.quat))
        inertia = body.find('inertial')
        for attr, value in [('pos', original.ipos), ('quat', original.iquat), ('diaginertia', original.inertia)]:
            inertia.set(attr, numbers(value))
        inertia.set('mass', numbers([original.mass[0]]))
        for index, geom in enumerate(body.findall('geom')):
            geom.set('name', body.get('name')+('_visual' if index == 0 else '_collision'))
            if index != 0:
                geom.set('friction', '.7 .005 .0001')
    for joint in root.findall('.//body/joint'):
        original = source.joint(joint.get('name'))
        joint.set('axis', numbers(original.axis))
        joint.set('pos', numbers(original.pos))
        joint.set('range', numbers(original.range))
        joint.set('damping', '.0001')
    primary = root.find(".//joint[@name='4C2_Joint1']")
    primary.set('actuatorfrcrange', '-.2 .2')
    for index, equality in enumerate(root.findall('equality/joint'), 1):
        equality.set('name', f'eg2_mimic_{index}')
        equality.set('solref', '.004 1')
        equality.set('solimp', '.999 .999 .001')
    contact = ET.SubElement(root, 'contact')
    for index, (one, two) in enumerate(INTERNAL_PAIRS):
        ET.SubElement(contact, 'exclude', name=f'eg2_internal_{index}', body1=one, body2=two)
    for body_name, side in [('4C2_Link5', 1), ('4C2_Link6', -1)]:
        body = root.find(f".//body[@name='{body_name}']")
        # Points on the distal flat contact land, measured in original STL/URDF
        # coordinates. They do not add contact or change mesh geometry.
        ET.SubElement(body, 'site', name='eg2_left_pad' if side == 1 else 'eg2_right_pad',
                      pos=numbers([side*.0177, .006, .027]), size='.0015', group='3', rgba='0 1 1 1')
    base = root.find("worldbody/body[@name='4C2_baselink']")
    ET.SubElement(base, 'site', name='gripper_mount', pos='0 0 0', size='.004', group='3', rgba='1 .6 0 1')
    # Fixed nominal TCP at q=.41; the real pad midpoint moves in Z with opening.
    z = .079+.0223*np.sin(.41)+.035591*np.cos(.41)+.027
    ET.SubElement(base, 'site', name='grasp_site', pos=numbers([0, 0, z]),
                  size='.003', group='3', rgba='1 0 1 1')
    actuator = ET.SubElement(root, 'actuator')
    ET.SubElement(actuator, 'position', name='eg2_position', joint='4C2_Joint1',
                  kp='.05', kv='.002', ctrllimited='true', ctrlrange='0 .82',
                  forcelimited='true', forcerange='-.2 .2')
    signs = {'4C2_Joint1': 1, '4C2_Joint2': 1, '4C2_Joint3': -1,
             '4C2_Joint4': -1, '4C2_Joint5': 1, '4C2_Joint6': 1}
    q = source.qpos0.copy()
    for name, sign in signs.items():
        q[source.joint(name).qposadr[0]] = sign*.82
    ET.SubElement(ET.SubElement(root, 'keyframe'), 'key', name='home', qpos=numbers(q), ctrl='.82')
    standalone = deepcopy(root)
    for body in standalone.findall('.//body'):
        body.set('gravcomp', '1')
    for joint in standalone.findall('.//body/joint'):
        joint.set('actuatorgravcomp', 'true')
    write(standalone, ASSETS/'eg2_4c2.xml')
    standalone_model = mujoco.MjModel.from_xml_path(str(ASSETS/'eg2_4c2.xml'))
    if (standalone_model.nq, standalone_model.nv, standalone_model.nu, standalone_model.neq) != (6, 6, 1, 5):
        raise ValueError('Unexpected standalone structure')

    combined = ET.parse(ROBOT_ASSETS/'rml63_dynamics.xml').getroot()
    combined.set('model', 'RML63II-6F-V + EG2-4C2 experimental aligned 8mm adapter')
    combined.insert(0, ET.Comment('Experimental assembly, not a verified 6F-V stack; see gripper SOURCE.md.'))
    combined.find('compiler').attrib.pop('meshdir', None)
    for mesh in combined.findall('asset/mesh'):
        path = ROBOT_ASSETS/'upstream/meshes'/Path(mesh.get('file')).name
        mesh.set('file', os.path.relpath(path, ASSETS))
    combined.find('asset').extend(deepcopy(list(root.find('asset'))))
    flange = combined.find(".//body[@name='link_6']")
    adapter = ET.SubElement(flange, 'body', name='eg2_experimental_adapter')
    # Drawing: thickness 8mm, diameter 57mm; weight .011 interpreted as kg.
    # Coaxial alignment and seating depth are an experimental fixture choice.
    radius, height, mass = .0285, .008, .011
    inertia_xy = mass*(3*radius**2+height**2)/12
    ET.SubElement(adapter, 'inertial', pos='0 0 .004', mass=str(mass),
                  diaginertia=numbers([inertia_xy, inertia_xy, mass*radius**2/2]))
    ET.SubElement(adapter, 'geom', name='eg2_adapter_proxy', type='cylinder',
                  pos='0 0 .004', size='.0285 .004', rgba='.2 .3 .5 1')
    mounted = deepcopy(base)
    mounted.set('pos', '0 0 .008')
    adapter.append(mounted)
    for section in ['equality', 'actuator', 'contact']:
        target = combined.find(section)
        if target is None:
            target = ET.SubElement(combined, section)
        target.extend(deepcopy(list(root.find(section))))
    # Copy scene fixtures without editing the existing robot or scene files.
    scene = ET.parse(ROBOT_ASSETS/'scene.xml').getroot()
    for element in scene:
        if element.tag == 'include':
            continue
        if element.tag == 'worldbody':
            combined.find('worldbody').extend(deepcopy(list(element)))
        else:
            combined.append(deepcopy(element))
    key = combined.find('keyframe/key')
    arm_q, arm_ctrl = key.get('qpos'), key.get('ctrl')
    key.set('qpos', arm_q+' '+numbers(q))
    key.set('ctrl', arm_ctrl+' .82')
    output = ASSETS/'rml63_eg2_4c2.xml'
    write(combined, output)
    compiled = mujoco.MjModel.from_xml_path(str(output))
    if (compiled.nq, compiled.nv, compiled.nu, compiled.neq) != (12, 12, 7, 5):
        raise ValueError('Unexpected combined structure')
    print(f'Built {output}: nq={compiled.nq}, nv={compiled.nv}, nu={compiled.nu}, neq={compiled.neq}')


if __name__ == '__main__':
    build()
